#!/usr/bin/env node

import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";
const PRICE_KEYS = [
  "input_cost_per_token",
  "output_cost_per_token",
  "cache_read_input_token_cost",
  "cache_creation_input_token_cost",
];

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src/model-prices-litellm.ts");

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Failed to fetch LiteLLM prices: ${response.status} ${response.statusText}`);
}

const raw = await response.json();
const prices = Object.fromEntries(
  Object.entries(raw)
    .map(([model, value]) => [model, pickPriceFields(value)])
    .filter(([, value]) => Object.keys(value).length > 0)
    .sort(([left], [right]) => left.localeCompare(right)),
);

await writeFile(
  outputPath,
  [
    "/* This file is generated by scripts/refresh-litellm-model-prices.mjs. */",
    `export const LITELLM_PRICING_SOURCE = ${JSON.stringify(SOURCE_URL)};`,
    "",
    "export interface LiteLLMModelPrice {",
    "  input_cost_per_token?: number;",
    "  output_cost_per_token?: number;",
    "  cache_read_input_token_cost?: number;",
    "  cache_creation_input_token_cost?: number;",
    "}",
    "",
    "export const LITELLM_MODEL_PRICES = ",
    `${JSON.stringify(prices, null, 2)} as const satisfies Record<string, LiteLLMModelPrice>;\n`,
  ].join("\n"),
);

console.log(`Wrote ${Object.keys(prices).length} LiteLLM price records to ${outputPath}`);

function pickPriceFields(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return {};
  }
  return Object.fromEntries(
    PRICE_KEYS.flatMap((key) => {
      const rawValue = value[key];
      return typeof rawValue === "number" && Number.isFinite(rawValue)
        ? [[key, rawValue]]
        : [];
    }),
  );
}
